def _vague_pair(idx: int) -> Tuple[str, str]:
    template = random.choice(VAGUE_TEMPLATES)
    noun = random.choice(NOUNS)
    topic = random.choice(TOPICS)
    verb = random.choice(VERBS)

    if "{noun}" in template:
        prompt = template.replace("{noun}", noun)
    elif "{topic}" in template:
        prompt = template.replace("{topic}", topic)
    elif "{verb}" in template:
        prompt = template.replace("{verb}", verb).replace("{noun}", random.choice(NOUNS))
    else:
        prompt = template

    questions = (
        "Role: What role or persona should take on this task?\n"
        f"Context: What background or situation should I know about '{prompt}'?\n"
        "Focus: What is the specific goal or task you want accomplished?\n"
        "Output: What format or deliverable do you expect?"
    )
    return prompt, questions


def _clear_pair(idx: int) -> Tuple[str, str]:
    role = random.choice(ROLES)
    context = random.choice(CONTEXTS)
    focus = random.choice(FOCUSES)
    output = random.choice(OUTPUTS)

    prompt = f"As a {role}, {focus.capitalize()} in the context of {context}, and {output}."

    formatted = (
        f"Role: {role.capitalize()}\n"
        f"Context: {context}\n"
        f"Focus: {focus}\n"
        f"Output: {output}"
    )
    return prompt, formatted


def build_dataset(target_pairs: int = TARGET_PAIRS) -> dict:
    """Build a synthetic dataset with target_pairs total pairs."""
    half = target_pairs // 2
    vague_pairs = [_vague_pair(i) for i in range(half)]
    clear_pairs = [_clear_pair(i + half) for i in range(target_pairs - half)]

    all_pairs = vague_pairs + clear_pairs
    random.shuffle(all_pairs)

    vague_list = [{"input": p, "target": q} for p, q in all_pairs if "Role: What role" in q]
    clear_list = [{"input": p, "target": q} for p, q in all_pairs if "Role:" in q and "What role" not in q]

    return {
        "version": "3.0.0-expanded",
        "description": (
            "Expanded synthetic dataset for Inspector AI critical thinking training. "
            "20,000+ pairs NOT from the original OpenAssistant/mock sets. "
            "Part 1 maps vague prompts to clarification questions; "
            "Part 2 maps clear prompts to R.C.F.O formatted prompts."
        ),
        "splits": {
            "vague_to_questions": vague_list,
            "clear_to_rcfo": clear_list,
        },
        "counts": {
            "vague_to_questions": len(vague_list),
            "clear_to_rcfo": len(clear_list),
            "total": len(vague_list) + len(clear_list),
        },
    }


def save_json(data: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def main() -> None:
    RAW_DATA_DIR.mkdir(parents=True, exist_ok=True)
    PROCESSED_DATA_DIR.mkdir(parents=True, exist_ok=True)

    dataset = build_dataset(TARGET_PAIRS)

    save_json(dataset, OUTPUT_PATH)
    save_json(dataset, RAW_DATA_DIR / "expanded_dataset.json")

    print("Inspector AI — expanded dataset built successfully.")
